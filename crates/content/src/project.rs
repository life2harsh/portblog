#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShapeFamily {
    Knot,
    Orbit,
    Lattice,
    Ribbon,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ArtConfig {
    pub shape: ShapeFamily,
    pub rotation_x: f64,
    pub rotation_y: f64,
    pub twist: f64,
    pub radius: f64,
    pub secondary_radius: f64,
    pub density: u32,
    pub warp: f64,
    pub symmetry: f64,
    pub phase: f64,
    pub scale: f64,
    pub seed: u64,
}

impl ArtConfig {
    pub fn lerp(&self, target: &ArtConfig, t: f64) -> ArtConfig {
        let t = t.clamp(0.0, 1.0);
        ArtConfig {
            shape: if t < 0.5 { self.shape } else { target.shape },
            rotation_x: self.rotation_x + (target.rotation_x - self.rotation_x) * t,
            rotation_y: self.rotation_y + (target.rotation_y - self.rotation_y) * t,
            twist: self.twist + (target.twist - self.twist) * t,
            radius: self.radius + (target.radius - self.radius) * t,
            secondary_radius: self.secondary_radius
                + (target.secondary_radius - self.secondary_radius) * t,
            density: (self.density as f64 + (target.density as f64 - self.density as f64) * t)
                .round() as u32,
            warp: self.warp + (target.warp - self.warp) * t,
            symmetry: self.symmetry + (target.symmetry - self.symmetry) * t,
            phase: self.phase + (target.phase - self.phase) * t,
            scale: self.scale + (target.scale - self.scale) * t,
            seed: if t < 0.5 { self.seed } else { target.seed },
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProjectStatus {
    Active,
    InProgress,
}

impl ProjectStatus {
    pub fn label(&self) -> &'static str {
        match self {
            ProjectStatus::Active => "active",
            ProjectStatus::InProgress => "in progress",
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct ProjectLink {
    pub label: &'static str,
    pub url: &'static str,
}

